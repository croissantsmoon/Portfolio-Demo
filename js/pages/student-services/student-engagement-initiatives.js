function openEngagementModal(id) {
  var activity = null;
  for (var i = 0; i < engagementActivities.length; i++) {
    if (engagementActivities[i].id === id) { activity = engagementActivities[i]; break; }
  }
  if (!activity) return;
  var modal = document.getElementById('student-modal');
  var body = document.getElementById('student-modal-body');
  body.innerHTML = buildModalHTML(activity, activity.highlightsLabel);
  modal.classList.remove('hidden');
  modal.classList.add('flex');
  document.body.style.overflow = 'hidden';
  if (window.lucide) lucide.createIcons();
}
